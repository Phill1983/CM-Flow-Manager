#!/usr/bin/env node
/**
 * Generate synthetic PDF fixtures for Phase 2 tests.
 * Passwords are fake PoC values — never reuse real document credentials.
 */
import { mkdir, writeFile, copyFile, rm } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
import { existsSync } from 'node:fs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const REPO = resolve(ROOT, '../..');
const OUT = join(ROOT, 'fixtures');
const QPDF = process.env.CMFLOW_QPDF_PATH || join(REPO, 'vendor/qpdf/bin/qpdf.exe');

const KNOWN_PASSWORD = 'poc-known-pass';
const ALT_PASSWORD = 'poc-alt-pass';

function runQpdf(args) {
  const result = spawnSync(QPDF, args, { encoding: 'utf8', shell: false, windowsHide: true });
  // qpdf uses exit 3 for warnings-with-success in some cases
  if (result.status !== 0 && result.status !== 3) {
    throw new Error(`qpdf failed (${result.status}): ${result.stderr || result.stdout}`);
  }
  return result;
}

async function main() {
  if (!existsSync(QPDF)) {
    throw new Error(`qpdf not found at ${QPDF}. Run: pnpm fetch:qpdf`);
  }
  await mkdir(OUT, { recursive: true });

  const plain = join(OUT, 'plain.pdf');
  const tmp = join(OUT, '_tmp_plain.pdf');
  await rm(tmp, { force: true });
  runQpdf(['--empty', tmp]);
  await copyFile(tmp, plain);
  await rm(tmp, { force: true });
  await rm(join(OUT, 'plain.normalized.pdf'), { force: true });

  const known = join(OUT, 'encrypted-known-password.pdf');
  runQpdf([
    '--encrypt',
    `--user-password=${KNOWN_PASSWORD}`,
    `--owner-password=${KNOWN_PASSWORD}`,
    '--bits=256',
    '--',
    plain,
    known,
  ]);

  const alt = join(OUT, 'encrypted-alternate-password.pdf');
  runQpdf([
    '--encrypt',
    `--user-password=${ALT_PASSWORD}`,
    `--owner-password=${ALT_PASSWORD}`,
    '--bits=256',
    '--',
    plain,
    alt,
  ]);

  await writeFile(join(OUT, 'corrupted.pdf'), '%PDF-1.4\nthis is not a valid pdf structure\n', 'utf8');

  await writeFile(
    join(OUT, 'README.md'),
    `# PDF fixtures (synthetic)

Generated by \`packages/pdf-engine/scripts/generate-fixtures.mjs\` using official qpdf.

| File | Notes |
| --- | --- |
| plain.pdf | Unencrypted empty PDF from \`qpdf --empty\` |
| encrypted-known-password.pdf | Password: \`poc-known-pass\` |
| encrypted-alternate-password.pdf | Password: \`poc-alt-pass\` |
| corrupted.pdf | Intentionally invalid |

Do not use real customer documents. Regenerate with \`pnpm fixtures:pdf\`.
`,
    'utf8',
  );

  console.log(`Fixtures written to ${OUT}`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
